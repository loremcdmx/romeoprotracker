export function fmtDateShortLang(ts, lang) {
  const parts = warsawParts(ts)
  if (!parts) return '—'
  return `${parts.day} ${(MONTHS_SHORT_BY_LANG[lang] || MONTHS_SHORT_BY_LANG.ru)[parts.month - 1]}`
}

