export const START_BANKROLL = 10000

// meta.json-shaped object for the first `count` real sessions, optionally
// followed by extra sessions { dt (seconds after the previous one), result, tournaments }.
export function replayMeta(count = REAL_HISTORY.length, extra = []) {
  const brHistory = REAL_HISTORY.slice(0, count).map(([timestamp, brAfter, sessionResult, tournaments, totalTournaments], i) => ({
    id: `real-${i}`, date: `D${i + 1}`, timestamp, brAfter, sessionResult, tournaments, totalTournaments,
    text: `Session ${i + 1}`,
  }))
  let last = brHistory[brHistory.length - 1]
  extra.forEach(({ dt, result, tournaments }, i) => {
    last = {
      id: `extra-${i}`, date: `E${i + 1}`, timestamp: last.timestamp + dt,
      brAfter: last.brAfter + result, sessionResult: result, tournaments,
      totalTournaments: last.totalTournaments + tournaments, text: `Extra session ${i + 1}`,
    }
    brHistory.push(last)
  })
  return {
    startBankroll: START_BANKROLL, targetBankroll: 10000000, bankroll: last.brAfter, day: brHistory.length,
    totalTournaments: last.totalTournaments, brHistory, lastUpdated: new Date((last.timestamp + 1800) * 1000).toISOString(),
  }
}
